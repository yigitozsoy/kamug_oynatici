def t(key: str, **kw) -> str:
    pair = S.get(key)
    if pair is None:
        return key
    lang = prefs.get("language", "tr")
    text = pair[0] if lang == "tr" else pair[1]
    if kw:
        try:
            text = text.format(**kw)
        except (KeyError, IndexError, ValueError):
            pass
    return text
